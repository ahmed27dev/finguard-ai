"""
metric_extractor.py - Step 4 of the pipeline. First file of the flagging track.

Turns the linearized rows from retrieval into a clean set of metrics the
anomaly detector can do arithmetic on.

Not every linearized row is a financial metric. Apple's 364 rows include a
stock performance index based at 100, earnings per share, share counts in
thousands, and the same revenue figure repeated in four different tables.
Feeding all of that to a threshold rule produces confident nonsense: a
14% "anomaly" in an index that tracks share price, or four duplicate flags
for one revenue decline.

So this file does three things:

  FILTER      drop rows that are not dollar-denominated metrics
  CANONICALISE map filer-specific labels onto shared names, so "Total net
              sales" and "Total revenue" are the same metric across filings
  DEDUPLICATE keep one entry per metric per source, not one per table

Usage:
    python -m flagging.metric_extractor aapl-2025
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

PROCESSED = Path("data/processed")

# Multipliers to a common base, so figures from different tables are
# comparable. A filing that reports in thousands and one that reports in
# millions must not be compared as raw numbers.
SCALE_FACTOR = {"thousands": 1_000, "millions": 1_000_000, "billions": 1_000_000_000}

# Sections that contain tables but not financial metrics. Item 5 holds the
# stock performance graph and share repurchase tables.
SKIP_SECTIONS = ("item 5",)

# Row labels that are per-share, per-unit, or counts rather than amounts.
SKIP_LABEL_RE = re.compile(
    r"per[- ]share|per share|per rsu|earnings per|"
    r"\bbasic\b|\bdiluted\b|shares outstanding|weighted[- ]average|"
    r"number of shares|par value|\bindex\b|"
    r"s&p|dow jones|nasdaq",
    re.I,
)

# Canonical metric names. Order matters: the first pattern that matches
# wins, so more specific patterns come first.
CANONICAL_PATTERNS: list[tuple[str, re.Pattern]] = [
    ("cost_of_revenue", re.compile(r"^total cost of (sales|revenue)$|^cost of (sales|revenue)$", re.I)),
    ("gross_profit", re.compile(r"^(total )?gross (margin|profit)$", re.I)),
    ("rnd_expense", re.compile(r"^research and development$", re.I)),
    ("sga_expense", re.compile(r"^selling, general and administrative$|^general and administrative$", re.I)),
    ("operating_expenses", re.compile(r"^total operating expenses$", re.I)),
    ("operating_income", re.compile(r"^operating income(/\(loss\))?$", re.I)),
    ("pretax_income", re.compile(
        r"^income before (provision for )?income taxes$|"
        r"^income before taxes$|^pre-?tax income$", re.I)),
    ("tax_provision", re.compile(r"^provision for income taxes$", re.I)),
    ("net_income", re.compile(r"^net income(/\(loss\))?$", re.I)),
    ("revenue", re.compile(r"^total (net sales|revenue|revenues)$|^net sales$|^revenue$", re.I)),
    ("total_assets", re.compile(r"^total assets$", re.I)),
    ("total_liabilities", re.compile(r"^total liabilities$", re.I)),
    ("equity", re.compile(r"^total (shareholders'|stockholders') equity$", re.I)),
    ("cash", re.compile(r"^cash and cash equivalents$", re.I)),
    ("inventory", re.compile(r"^inventories$|^inventory$", re.I)),
    ("receivables", re.compile(r"^accounts receivable, net$", re.I)),
    ("operating_cash_flow", re.compile(
        r"^(net )?cash (generated by|provided by|used in|from) operating activities$",
        re.I)),
    ("current_assets", re.compile(r"^total current assets$", re.I)),
    ("current_liabilities", re.compile(r"^total current liabilities$", re.I)),
    ("term_debt", re.compile(r"^term debt$|^long[- ]term debt$", re.I)),
]


def canonical_name(label: str) -> str | None:
    """Map a filer's row label onto a shared metric name, or None."""
    clean = label.strip().rstrip(":").strip()
    # Strip footnote markers such as "Services (1)".
    clean = re.sub(r"\s*\(\d+\)(\(\d+\))*\s*$", "", clean)
    for name, pattern in CANONICAL_PATTERNS:
        if pattern.match(clean):
            return name
    return None


def is_usable(row: dict) -> tuple[bool, str]:
    """
    Decide whether a linearized row is a financial metric.

    Returns (usable, reason) so the reasons can be counted - a filter that
    silently drops 90% of rows is worse than no filter.
    """
    if row.get("layout") == "stacked":
        return False, "single-period (use merged_series instead)"

    if any(s in (row.get("section") or "").lower() for s in SKIP_SECTIONS):
        return False, "non-financial section"

    label = row.get("label", "")
    if SKIP_LABEL_RE.search(label):
        return False, "per-share, count or index"

    values = row.get("values") or {}
    periods = [p for p in values if re.fullmatch(r"(19|20)\d{2}", str(p))]
    if len(periods) < 2:
        return False, "fewer than two periods"

    if not row.get("scale"):
        return False, "units unknown"

    return True, "ok"


def extract_metrics(linear: list[dict]) -> list[dict]:
    """
    Build the metric list the anomaly detector consumes.

    Values are kept in their reported scale and also given in absolute
    terms, so rules can use whichever they need without re-deriving it.
    """
    metrics: list[dict] = []
    seen: dict[tuple, int] = {}

    for row in linear:
        usable, _ = is_usable(row)
        if not usable:
            continue

        values = {
            str(p): float(v)
            for p, v in row["values"].items()
            if re.fullmatch(r"(19|20)\d{2}", str(p))
        }
        factor = SCALE_FACTOR.get(row["scale"], 1)
        canonical = canonical_name(row["label"])

        # Deduplicate: the same figures under the same name, however many
        # tables repeat them, is one metric. Apple states total net sales
        # in four separate tables.
        key = (canonical or row["label"].lower(), tuple(sorted(values.items())))
        if key in seen:
            metrics[seen[key]]["also_on_pages"].append(row["page"])
            continue

        seen[key] = len(metrics)
        metrics.append(
            {
                "metric_id": f"m_{len(metrics):04d}",
                "canonical": canonical,
                "label": row["label"],
                "values": values,
                "absolute": {p: v * factor for p, v in values.items()},
                "scale": row["scale"],
                "scale_source": row.get("scale_source"),
                "layout": row["layout"],
                "page": row["page"],
                "section": row["section"],
                "source_row_id": row["row_id"],
                "also_on_pages": [],
                "is_primary": False,
                "role": "unnamed",
            }
        )

    metrics = _merge_period_subsets(metrics)
    _assign_primary(metrics)
    for i, m in enumerate(metrics):
        m["metric_id"] = f"m_{i:04d}"
    return metrics


def _merge_period_subsets(metrics: list[dict]) -> list[dict]:
    """
    Collapse series that are the same metric seen over different spans.

    Microsoft reports cost of revenue twice: once with two years and once
    with three. They agree on the overlapping years, so they are one series
    reported in two tables, not two metrics. Keep the longer.
    """
    metrics = sorted(metrics, key=lambda m: -len(m["values"]))
    kept: list[dict] = []

    for m in metrics:
        absorbed = False
        for k in kept:
            if k["canonical"] != m["canonical"] or k["label"] != m["label"]:
                continue
            shared = set(k["values"]) & set(m["values"])
            if shared and all(k["values"][p] == m["values"][p] for p in shared) \
                    and set(m["values"]) <= set(k["values"]):
                k["also_on_pages"].append(m["page"])
                absorbed = True
                break
        if not absorbed:
            kept.append(m)
    return kept


def _assign_primary(metrics: list[dict]) -> None:
    """
    Mark one series per canonical name as the company-wide figure.

    The same label appears at company level and again for every segment or
    line of business: Microsoft labels four different series "Revenue",
    JPMorgan reports nine different "Total assets". Comparing a segment's
    revenue against company operating income would produce a confident
    nonsense flag, so only the primary carries the canonical name.

    Chosen by magnitude first, then period coverage. Magnitude is the more
    reliable signal: a company total is never smaller than any of its parts,
    and a balance is never smaller than the change in that balance. Ranking
    by period count first got inventory wrong - a balance sheet shows two
    dates while the cash flow statement shows three, so the change in
    inventory outranked the inventory balance itself.
    """
    by_name: dict[str, list[dict]] = {}
    for m in metrics:
        if m["canonical"]:
            by_name.setdefault(m["canonical"], []).append(m)

    for name, candidates in by_name.items():
        def rank(m: dict) -> tuple:
            biggest = max(abs(v) for v in m["values"].values())
            return (biggest, len(m["values"]))

        winner = max(candidates, key=rank)
        for m in candidates:
            if m is winner:
                m["is_primary"] = True
                m["role"] = "company"
            else:
                # Still a usable metric, just not the company-wide one.
                m["is_primary"] = False
                m["role"] = "component"
                m["component_of"] = name
                m["canonical"] = None


def summarise(linear: list[dict], metrics: list[dict]) -> None:
    reasons: dict[str, int] = {}
    for row in linear:
        _, reason = is_usable(row)
        reasons[reason] = reasons.get(reason, 0) + 1

    print(f"linear rows in : {len(linear)}")
    for reason, count in sorted(reasons.items(), key=lambda kv: -kv[1]):
        print(f"   {count:>5}  {reason}")
    print(f"metrics out    : {len(metrics)}  "
          f"(after deduplicating repeated tables)")

    named = [m for m in metrics if m["canonical"]]
    components = [m for m in metrics if m.get("role") == "component"]
    print(f"company-wide   : {len(named)} canonical metrics")
    print(f"components     : {len(components)} segment/line-item series "
          f"(kept, but not canonical)")
    for m in sorted(named, key=lambda x: x["canonical"]):
        periods = sorted(m["values"], reverse=True)
        series = " | ".join(f"{p}: {m['values'][p]:,.0f}" for p in periods[:3])
        print(f"   {m['canonical']:<20} p{m['page']:<4} {series}")


def main() -> None:
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)

    filing_id = sys.argv[1]
    src = PROCESSED / f"{filing_id}.linear.json"
    if not src.exists():
        raise SystemExit(f"missing {src} - run pipeline.py {filing_id} first")

    linear = json.loads(src.read_text(encoding="utf-8"))
    metrics = extract_metrics(linear)

    out = PROCESSED / f"{filing_id}.metrics.json"
    out.write_text(json.dumps(metrics, indent=2), encoding="utf-8")

    summarise(linear, metrics)
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()